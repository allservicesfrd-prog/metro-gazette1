/**
 * Metro-Gazette social-preview worker
 *
 * Bind this Worker to metrogazette.net/* and configure these Worker variables:
 *   SITE_ORIGIN=https://YOUR-GITHUB-PAGES-ORIGIN/
 *   FIREBASE_PROJECT_ID=metro-gazette
 *   FIREBASE_API_KEY=your Firebase web API key
 *
 * SITE_ORIGIN must be the origin that serves index.html (not metrogazette.net),
 * otherwise the Worker would fetch itself in a loop.
 */

const SOCIAL_BOTS = /facebookexternalhit|facebot|twitterbot|whatsapp|linkedinbot|slackbot|discordbot|telegrambot|pinterestbot|googlebot/i;
const DEFAULT_IMAGE = 'https://metrogazette.net/metro-gazette-social.jpg';
const DEFAULT_DESCRIPTION = 'Metro-Gazette delivers timely, accurate reporting from the Dominican Republic, the Caribbean, and around the world.';

export default {
  async fetch(request, env) {
    const requestUrl = new URL(request.url);
    const articleId = requestUrl.searchParams.get('article');
    const userAgent = request.headers.get('user-agent') || '';

    // Only article links requested by social crawlers need server-rendered tags.
    if (!articleId || !SOCIAL_BOTS.test(userAgent)) {
      return fetchFromSiteOrigin(request, env);
    }

    // Firestore document IDs generated by this site are safe alphanumeric IDs.
    if (!/^[A-Za-z0-9_-]{1,128}$/.test(articleId)) {
      return fetchFromSiteOrigin(request, env);
    }

    const [siteResponse, article] = await Promise.all([
      fetchFromSiteOrigin(request, env),
      fetchArticle(articleId, env)
    ]);

    if (!siteResponse.ok || !article) return siteResponse;

    const pageHtml = await siteResponse.text();
    const articleUrl = `https://metrogazette.net/?article=${encodeURIComponent(articleId)}`;
    const title = article.title || 'Metro Gazette — News That Matters';
    const description = shorten(article.dek || article.body || DEFAULT_DESCRIPTION, 200);
    const image = article.imageUrl || DEFAULT_IMAGE;
    const socialTags = createSocialTags({ title, description, image, articleUrl, publishedAt: article.date });
    const htmlWithTags = injectSocialTags(pageHtml, socialTags);

    const headers = new Headers(siteResponse.headers);
    headers.set('content-type', 'text/html; charset=UTF-8');
    // Never serve a stale tag set from Cloudflare's cache after an article is edited.
    headers.set('cache-control', 'no-store');
    return new Response(htmlWithTags, { status: siteResponse.status, statusText: siteResponse.statusText, headers });
  }
};

async function fetchFromSiteOrigin(request, env) {
  if (!env.SITE_ORIGIN) throw new Error('SITE_ORIGIN Worker variable is not configured.');
  const origin = new URL(env.SITE_ORIGIN);
  const incoming = new URL(request.url);
  // Preserve an optional GitHub Pages project path in SITE_ORIGIN.
  const basePath = origin.pathname.replace(/\/$/, '');
  const incomingPath = incoming.pathname === '/' ? '' : incoming.pathname;
  origin.pathname = `${basePath}${incomingPath}` || '/';
  origin.search = incoming.search;
  return fetch(new Request(origin.toString(), {
    method: request.method,
    headers: request.headers,
    redirect: 'follow'
  }));
}

async function fetchArticle(articleId, env) {
  if (!env.FIREBASE_PROJECT_ID || !env.FIREBASE_API_KEY) {
    throw new Error('Firebase Worker variables are not configured.');
  }
  const endpoint = `https://firestore.googleapis.com/v1/projects/${encodeURIComponent(env.FIREBASE_PROJECT_ID)}/databases/(default)/documents/articles/${encodeURIComponent(articleId)}?key=${encodeURIComponent(env.FIREBASE_API_KEY)}`;
  const response = await fetch(endpoint);
  if (!response.ok) return null;
  const document = await response.json();
  const fields = document.fields || {};
  return {
    title: firestoreValue(fields.title),
    dek: firestoreValue(fields.dek),
    body: firestoreValue(fields.body),
    imageUrl: firestoreValue(fields.imageUrl),
    date: firestoreValue(fields.date)
  };
}

function firestoreValue(field) {
  if (!field) return '';
  return field.stringValue || field.timestampValue || field.integerValue || '';
}

function shorten(value, maxLength) {
  const plainText = String(value)
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/\s+/g, ' ')
    .trim();
  return plainText.length > maxLength ? `${plainText.slice(0, maxLength - 1).trim()}…` : plainText;
}

function escapeHtml(value) {
  return String(value).replace(/[&<>'"]/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#39;', '"': '&quot;' })[char]);
}

function createSocialTags({ title, description, image, articleUrl, publishedAt }) {
  const safeTitle = escapeHtml(title);
  const safeDescription = escapeHtml(description);
  const safeImage = escapeHtml(image);
  const safeUrl = escapeHtml(articleUrl);
  const safeDate = escapeHtml(publishedAt || '');
  return `
    <title>${safeTitle}</title>
    <link rel="canonical" href="${safeUrl}">
    <meta name="description" content="${safeDescription}">
    <meta property="og:type" content="article">
    <meta property="og:site_name" content="Metro-Gazette">
    <meta property="og:title" content="${safeTitle}">
    <meta property="og:description" content="${safeDescription}">
    <meta property="og:image" content="${safeImage}">
    <meta property="og:image:alt" content="${safeTitle}">
    <meta property="og:url" content="${safeUrl}">
    ${safeDate ? `<meta property="article:published_time" content="${safeDate}">` : ''}
    <meta name="twitter:card" content="summary_large_image">
    <meta name="twitter:title" content="${safeTitle}">
    <meta name="twitter:description" content="${safeDescription}">
    <meta name="twitter:image" content="${safeImage}">
    <meta name="twitter:image:alt" content="${safeTitle}">`;
}

function injectSocialTags(html, socialTags) {
  // Remove generic title, canonical, description, Open Graph, and Twitter tags so
  // crawlers receive one unambiguous set of article metadata.
  const withoutExistingTags = html
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>\s*/gi, '')
    .replace(/<link\b(?=[^>]*\brel=["']canonical["'])[^>]*>\s*/gi, '')
    .replace(/<meta\b(?=[^>]*\b(?:property|name)=["'](?:og:[^"']+|twitter:[^"']+|description)["'])[^>]*>\s*/gi, '');
  return withoutExistingTags.replace(/<\/head\s*>/i, `${socialTags}\n</head>`);
}
